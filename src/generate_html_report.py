"""Generate an interactive HTML dashboard from insurance pipeline CSV outputs.

Reads the same CSVs produced by ``src/transform.py`` and ``src/model.py`` and
assembles a self-contained, single-file HTML dashboard with interactive Plotly
charts.  The Plotly JS bundle is embedded inline from the installed package so
no web server or internet connection is required to view the file.

Charts included
---------------
* **KPIs** — paid totals and claim counts by member region, split by network status.
* **Monthly Trends** — paid totals over time, grouped by member region.
* **Loss Ratio** — billed / allowed / paid amounts side-by-side with loss ratio %.
* **Network Utilization** — pie chart of in-network vs out-of-network claims.
* **Diagnosis Summary** — top-10 ICD codes ranked by paid total.
* **Model Metrics** — accuracy card from the predictive model run.

Usage
-----
    python -m src.generate_html_report \\
        --output-dir outputs/client_a \\
        --client-name "Client A" \\
        --out outputs/client_a/dashboard.html
"""

